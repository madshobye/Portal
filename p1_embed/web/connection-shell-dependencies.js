export function createConnectionShellDependencies({
  alphaEnableWebRtcConnect,
  alphaEnableWebSocketConnect,
  connectionHistoryLimit,
  connectionKindAvailable,
  connectionKindIcon,
  connectionKindLabel,
  currentDeviceDisplayName,
  defaultPeerIdFromWebSocket,
  documentRef,
  fields,
  getConnectionHistoryActions,
  getConnectionMemoryService,
  getConnectionReconnectService,
  getConnectionTransportSession,
  getConsoleController,
  getMqttShellService,
  isLoopbackHost,
  isMqttKind,
  isWebRtcKind,
  localStorageRef,
  markConnectionAttemptFailed,
  markConnectionAttemptStarted,
  navigatorRef,
  normalizeMqttHistoryConfig,
  normalizePeerId,
  normalizeUsbHint,
  normalizeWebSocketUrl,
  pickPortFromHint,
  state,
  storage,
  usbHintFromParams,
  usbHintLabel,
  usbStartupOptions,
  windowRef,
  wsDisplayName,
} = {}) {
  return {
    alphaEnableWebRtcConnect,
    alphaEnableWebSocketConnect,
    connectionHistoryLimit,
    connectionKindAvailable,
    connectionKindIcon,
    connectionKindLabel,
    currentDeviceDisplayName: () => currentDeviceDisplayName({
      lastInfo: state.lastInfo,
      lastStatus: state.lastStatus,
      lastConfig: state.lastConfig,
      normalizePeerId,
    }),
    defaultPeerIdFromWebSocket,
    documentRef,
    fields,
    getClient: () => state.client,
    getConnectionHistoryActions,
    getConnectionMemoryService,
    getConnectionReconnectService,
    getConnectionTransportSession,
    getConsoleController,
    getMqttShellService,
    getTransport: () => state.transport,
    isBusy: () => state.isBusy,
    isConnectionVerified: () => state.connectionVerified,
    isLoopbackHost,
    isMqttKind,
    isWebRtcKind,
    localStorageRef,
    markConnectionAttemptFailed,
    markConnectionAttemptStarted,
    navigatorRef,
    normalizeMqttHistoryConfig,
    normalizePeerId,
    normalizeUsbHint,
    normalizeWebSocketUrl,
    pickPortFromHint,
    setReconnectAfterReturn: (value) => {
      state.reconnectAfterReturn = value;
    },
    setReconnectAfterReturnAttempted: (value) => {
      state.reconnectAfterReturnAttempted = value;
    },
    storage,
    usbHintFromParams,
    usbHintLabel,
    usbStartupOptions,
    windowRef,
    wsDisplayName,
  };
}
