import { createProjectFeatureRegistry } from "./project-feature-registry.js?v=0.1.87-ui745";

export function createProjectAppFeatureRegistry({
  documentRef,
  getChatShellController,
  getCircuitShellController,
  getCircuitView,
  getCodeEditorShellController,
  getCommandConsoleService,
  getConsoleController,
  getDeviceStateController,
  getLegacyProjectMigrationService,
  getProjectDedupeService,
  getProjectDomainFeatureRegistry,
  getProjectSchemaMigrationService,
  getProjectToolbarController,
  getRevisionNameDialog,
  getSpecificationEditorController,
  getStartupStepRunner,
  getStorageDiagnostics,
  getTransportClient,
  getWindow,
  legacySketchMigrationId,
  legacySketchMigrationVersion,
  localStorageRef,
  normalizeChatMessages,
  normalizeCircuitLayout,
  normalizeSpecificationMode,
  projectCircuitForCurrentCode,
  projectLimit,
  projectStateAdapter,
  projectStoreName,
  readSpecificationMarkdown,
  revisionDraftVersion,
  sketchDbName,
  sketchDbVersion,
  sketchStoreName,
  storage,
  URLRef,
} = {}) {
  let projectFeatureRegistry = null;

  function getProjectFeatureRegistry() {
    if (projectFeatureRegistry) return projectFeatureRegistry;
    projectFeatureRegistry = createProjectFeatureRegistry({
      ...getProjectDomainFeatureRegistry().projectFeatureHelpers(),
      ...projectStateAdapter,
      documentRef,
      getChatShellController,
      getCircuitShellController,
      getCircuitView,
      getCodeEditorShellController,
      getCommandConsoleService,
      getConsoleController,
      getDeviceStateController,
      getLegacyProjectMigrationService,
      getProjectDedupeService,
      getProjectSchemaMigrationService,
      getProjectToolbarController,
      getRevisionNameDialog,
      getSpecificationEditorController,
      getStartupStepRunner,
      getStorageDiagnostics,
      getTransportClient,
      getWindow,
      legacySketchMigrationId,
      legacySketchMigrationVersion,
      localStorageRef,
      normalizeChatMessages,
      normalizeCircuitLayout,
      normalizeSpecificationMode,
      projectCircuitForCurrentCode,
      projectLimit,
      projectStoreName,
      readSpecificationMarkdown,
      revisionDraftVersion,
      sketchDbName,
      sketchDbVersion,
      sketchStoreName,
      storage,
      URLRef,
    });
    return projectFeatureRegistry;
  }

  return {
    getCurrentRevisionSession: () => getProjectFeatureRegistry().getCurrentRevisionSession(),
    getProjectActionsController: () => getProjectFeatureRegistry().getProjectActionsController(),
    getProjectController: () => getProjectFeatureRegistry().getProjectController(),
    getProjectDownloadService: () => getProjectFeatureRegistry().getProjectDownloadService(),
    getProjectFeatureRegistry,
    getProjectHistoryView: () => getProjectFeatureRegistry().getProjectHistoryView(),
    getProjectImporter: () => getProjectFeatureRegistry().getProjectImporter(),
    getProjectLibraryService: () => getProjectFeatureRegistry().getProjectLibraryService(),
    getProjectRevisionService: () => getProjectFeatureRegistry().getProjectRevisionService(),
    getProjectStore: () => getProjectFeatureRegistry().getProjectStore(),
    getRevisionDraftStore: () => getProjectFeatureRegistry().getRevisionDraftStore(),
  };
}
