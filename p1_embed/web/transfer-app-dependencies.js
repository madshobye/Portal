export function createTransferAppDependencies({
  getCodeEditorShellController,
  getCommandConsoleService,
  getConnectionShellController,
  getConsoleController,
  getDeviceRefreshService,
  getDeviceStateController,
  getGuinoController,
  getProjectController,
  getProjectDomainFeatureRegistry,
  getProjectLibraryService,
  getProjectRevisionService,
  getUploadStatusController,
  getViewShellController,
  inferCircuitLayout,
  isMqttKind,
  normalizeChatMessages,
  settle,
  state,
} = {}) {
  return {
    ...getProjectDomainFeatureRegistry().transferFeatureHelpers(),
    getClient: () => state.client,
    getCodeEditorShellController,
    getCommandConsoleService,
    getConnectionShellController,
    getConsoleController,
    getDeviceRefreshService,
    getDeviceStateController,
    getGuinoController,
    getLastConfig: () => state.lastConfig,
    getProjectController,
    getProjectLibraryService,
    getProjectRevisionService,
    getTransport: () => state.transport,
    getUploadStatusController,
    getViewShellController,
    inferCircuitLayout,
    isMqttKind,
    normalizeChatMessages,
    settle,
  };
}
