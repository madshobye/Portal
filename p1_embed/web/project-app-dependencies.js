export function createProjectAppDependencies({
  documentRef,
  getChatShellController,
  getCircuitShellController,
  getCircuitView,
  getCodeEditorShellController,
  getCommandConsoleService,
  getConsoleController,
  getDeviceStateController,
  getLegacyProjectMigrationService,
  getProjectDedupeService,
  getProjectDomainFeatureRegistry,
  getProjectRevisionService,
  getProjectSchemaMigrationService,
  getProjectStateAdapter,
  getProjectToolbarController,
  getRevisionNameDialog,
  getSpecificationEditorController,
  getStartupStepRunner,
  getStorageDiagnostics,
  legacySketchMigrationId,
  legacySketchMigrationVersion,
  localStorageRef,
  normalizeChatMessages,
  normalizeCircuitLayout,
  normalizeSpecificationMode,
  projectLimit,
  projectStoreName,
  revisionDraftVersion,
  sketchDbName,
  sketchDbVersion,
  sketchStoreName,
  state,
  storage,
  URLRef,
  windowRef,
} = {}) {
  return {
    documentRef,
    getChatShellController,
    getCircuitShellController,
    getCircuitView,
    getCodeEditorShellController,
    getCommandConsoleService,
    getConsoleController,
    getDeviceStateController,
    getLegacyProjectMigrationService,
    getProjectDedupeService,
    getProjectDomainFeatureRegistry,
    getProjectSchemaMigrationService,
    getProjectToolbarController,
    getRevisionNameDialog,
    getSpecificationEditorController,
    getStartupStepRunner,
    getStorageDiagnostics,
    getTransportClient: () => state.client,
    getWindow: () => windowRef,
    legacySketchMigrationId,
    legacySketchMigrationVersion,
    localStorageRef,
    normalizeChatMessages,
    normalizeCircuitLayout,
    normalizeSpecificationMode,
    projectCircuitForCurrentCode: (code) => getProjectRevisionService().projectCircuitForCurrentCode(code),
    projectLimit,
    projectStateAdapter: getProjectStateAdapter(),
    projectStoreName,
    readSpecificationMarkdown: () => getSpecificationEditorController().readMarkdown(),
    revisionDraftVersion,
    sketchDbName,
    sketchDbVersion,
    sketchStoreName,
    storage,
    URLRef,
  };
}
