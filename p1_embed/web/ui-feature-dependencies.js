export function createUiFeatureDependencies({
  fields,
  getChatShellController,
  getCircuitShellController,
  getCircuitView,
  getCodeEditorShellController,
  getConnectionUiStateController,
  getConsolePreferences,
  getCurrentRevisionSession,
  getFirmwareUpdateController,
  getGenerativePanelController,
  getGuinoController,
  getLowerPanelController,
  getMqttSettingsPanelController,
  getMqttSigninDialogController,
  getOnlineAuthListRenderer,
  getProjectActionsController,
  getProjectDomainFeatureRegistry,
  getSettingsTabs,
  getViewRouting,
  isMqttKind,
  normalizePeerId,
  projectSelectControls,
  requestAnimationFrameRef,
  revisionSelectControls,
  state,
  workspaceToolbars,
} = {}) {
  return {
    ...getProjectDomainFeatureRegistry().uiFeatureHelpers(),
    fields,
    getChatShellController,
    getCircuitShellController,
    getCircuitView,
    getCodeEditorShellController,
    getConnectionUiStateController,
    getConsolePreferences,
    getCurrentRevisionSession,
    getFirmwareUpdateController,
    getGenerativePanelController,
    getGuinoController,
    getLastConfig: () => state.lastConfig,
    getLastInfo: () => state.lastInfo,
    getLastStatus: () => state.lastStatus,
    getLowerPanelController,
    getMqttSettingsPanelController,
    getMqttSigninDialogController,
    getOnlineAuthListRenderer,
    getProjectActionsController,
    getSettingsTabs,
    getTransport: () => state.transport,
    getViewRouting,
    isMqttKind,
    normalizePeerId,
    requestAnimationFrameRef,
    projectSelectControls,
    revisionSelectControls,
    setWifiDraftDirty: (value) => {
      state.wifiDraftDirty = value;
    },
    workspaceToolbars,
  };
}
