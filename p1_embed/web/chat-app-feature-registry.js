import { createChatRegistry } from "./chat-registry.js?v=0.1.87-ui726";

export function createChatAppFeatureRegistry({
  builtInChatModelOptions,
  chatDefaultMaxOutputTokens,
  chatHardMaxOutputTokens,
  chatHistoryLimit,
  chatMinMaxOutputTokens,
  chatStateAdapter,
  createEncryptedChatKeyShareToken,
  cryptoAvailable,
  decryptEncryptedChatKeyShare,
  defaultChatModel,
  downloadText,
  fields,
  fetchRef,
  findGeneratedRevisionMatch,
  getChatDomainHelpers,
  getCodeEditorShellController,
  getConsoleController,
  getConnectionUiStateController,
  getLastError,
  getLastInfo,
  getLastStatus,
  getProjectController,
  getProjectLibraryService,
  getProjectRevisionService,
  getScriptUploadService,
  getSpecificationEditorController,
  getUiActionRunner,
  inferCircuitLayout,
  isEncryptedChatKeyShare,
  mergeGeneratedRevision,
  navigatorRef,
  normalizeChatMessages,
  normalizeCircuitLayout,
  normalizeSpecificationMode,
  projectStateAdapter,
  specificationModeLabel,
  specificationModePrompt,
  storage,
  updateCircuitView,
  windowRef,
} = {}) {
  let chatRegistry = null;

  function getChatRegistry() {
    if (chatRegistry) return chatRegistry;
    chatRegistry = createChatRegistry({
      ...getChatDomainHelpers(),
      ...projectStateAdapter,
      ...chatStateAdapter,
      builtInChatModelOptions,
      chatDefaultMaxOutputTokens,
      chatHardMaxOutputTokens,
      chatHistoryLimit,
      chatMinMaxOutputTokens,
      createEncryptedChatKeyShareToken,
      cryptoAvailable,
      decryptEncryptedChatKeyShare,
      defaultChatModel,
      downloadText,
      fields,
      fetchRef,
      findGeneratedRevisionMatch,
      getCodeEditorShellController,
      getConsoleController,
      getConnectionUiStateController,
      getLastError,
      getLastInfo,
      getLastStatus,
      getProjectController,
      getProjectLibraryService,
      getProjectRevisionService,
      getScriptUploadService,
      getSpecificationEditorController,
      getUiActionRunner,
      inferCircuitLayout,
      isEncryptedChatKeyShare,
      mergeGeneratedRevision,
      navigatorRef,
      normalizeChatMessages,
      normalizeCircuitLayout,
      normalizeSpecificationMode,
      specificationModeLabel,
      specificationModePrompt,
      storage,
      updateCircuitView,
      windowRef,
    });
    return chatRegistry;
  }

  return {
    getChatCompletionService: () => getChatRegistry().getChatCompletionService(),
    getChatCredentialActions: () => getChatRegistry().getChatCredentialActions(),
    getChatCredentials: () => getChatRegistry().getChatCredentials(),
    getChatRegistry,
    getChatSettings: () => getChatRegistry().getChatSettings(),
    getChatShellController: () => getChatRegistry().getChatShellController(),
    getChatTranscript: () => getChatRegistry().getChatTranscript(),
    getChatWorkflowController: () => getChatRegistry().getChatWorkflowController(),
  };
}
