export function createInfoAppDependencies({
  copyText,
  els,
  getCommandConsoleService,
  getConnectionAddressService,
  getConnectionShellController,
  getConnectionUiStateController,
  getConsoleController,
  getDeviceStateController,
  getFirmwareUpdateController,
  isMqttKind,
  isWebRtcKind,
  normalizePeerId,
  onGuinoAvailabilityChange,
  state,
  webVersion,
} = {}) {
  return {
    brandVersion: els.brandVersion,
    copyText,
    fields: els.fields,
    getClient: () => state.client,
    getCommandConsoleService,
    getConnectionAddressService,
    getConnectionShellController,
    getConnectionUiStateController,
    getConsoleController,
    getDeviceStateController,
    getFirmwareUpdateController,
    getLastConfig: () => state.lastConfig,
    getLastInfo: () => state.lastInfo,
    getLastStatus: () => state.lastStatus,
    getPeerInputValue: () => els.peerId.value,
    getScriptStateText: () => els.scriptState.textContent,
    getTransport: () => state.transport,
    getWebRtcPeerId: () => state.lastStatus?.webrtc?.peerId || "",
    getWebSocketUrl: () => els.websocketUrl.value,
    isMqttKind,
    isWebRtcKind,
    normalizePeerId,
    onGuinoAvailabilityChange,
    uiCanvas: els.uiCanvas,
    webVersion,
  };
}
