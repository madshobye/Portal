export function createChatAppDependencies({
  builtInChatModelOptions,
  chatDefaultMaxOutputTokens,
  chatHardMaxOutputTokens,
  chatHistoryLimit,
  chatMinMaxOutputTokens,
  createEncryptedChatKeyShareToken,
  cryptoAvailable,
  decryptEncryptedChatKeyShare,
  defaultChatModel,
  downloadText,
  fields,
  fetchRef,
  findGeneratedRevisionMatch,
  getChatStateAdapter,
  getCodeEditorShellController,
  getConsoleController,
  getConnectionUiStateController,
  getProjectController,
  getProjectDomainFeatureRegistry,
  getProjectLibraryService,
  getProjectRevisionService,
  getProjectStateAdapter,
  getScriptUploadService,
  getSpecificationEditorController,
  getUiActionRunner,
  getCircuitShellController,
  inferCircuitLayout,
  isEncryptedChatKeyShare,
  mergeGeneratedRevision,
  navigatorRef,
  normalizeChatMessages,
  normalizeCircuitLayout,
  normalizeSpecificationMode,
  specificationModeLabel,
  specificationModePrompt,
  state,
  storage,
  windowRef,
} = {}) {
  return {
    builtInChatModelOptions,
    chatDefaultMaxOutputTokens,
    chatHardMaxOutputTokens,
    chatHistoryLimit,
    chatMinMaxOutputTokens,
    createEncryptedChatKeyShareToken,
    cryptoAvailable,
    decryptEncryptedChatKeyShare,
    defaultChatModel,
    downloadText,
    fields,
    fetchRef,
    findGeneratedRevisionMatch,
    getChatDomainHelpers: () => getProjectDomainFeatureRegistry().chatFeatureHelpers(),
    getCodeEditorShellController,
    getConsoleController,
    getConnectionUiStateController,
    getLastError: () => state.lastStatus?.lastError || null,
    getLastInfo: () => state.lastInfo,
    getLastStatus: () => state.lastStatus,
    getProjectController,
    getProjectLibraryService,
    getProjectRevisionService,
    getScriptUploadService,
    getSpecificationEditorController,
    getUiActionRunner,
    inferCircuitLayout,
    isEncryptedChatKeyShare,
    mergeGeneratedRevision,
    normalizeChatMessages,
    normalizeCircuitLayout,
    normalizeSpecificationMode,
    navigatorRef,
    chatStateAdapter: getChatStateAdapter(),
    projectStateAdapter: getProjectStateAdapter(),
    specificationModeLabel,
    specificationModePrompt,
    storage,
    updateCircuitView: (status = "") => getCircuitShellController().update(status),
    windowRef,
  };
}
