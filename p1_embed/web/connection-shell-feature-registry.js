import { WebSerialTransport } from "./protocol/WebSerialTransport.js?v=0.1.87-ui350";
import { WebSocketTransport } from "./protocol/WebSocketTransport.js";
import { MqttWebRtcTransport } from "./protocol/MqttWebRtcTransport.js?v=0.1.87-ui348";
import { MqttTransport } from "./protocol/MqttTransport.js?v=0.1.87-ui348";
import { createConnectionShellRegistry } from "./connection-shell-registry.js?v=0.1.87-ui728";

export function createConnectionShellFeatureRegistry({
  alphaEnableWebRtcConnect,
  alphaEnableWebSocketConnect,
  connectionHistoryLimit,
  connectionKindAvailable,
  connectionKindIcon,
  connectionKindLabel,
  currentDeviceDisplayName,
  defaultPeerIdFromWebSocket,
  documentRef,
  fields,
  getClient,
  getConnectionHistoryActions,
  getConnectionMemoryService,
  getConnectionReconnectService,
  getConnectionTransportSession,
  getConsoleController,
  getMqttShellService,
  getTransport,
  isBusy,
  isConnectionVerified,
  isLoopbackHost,
  isMqttKind,
  isWebRtcKind,
  localStorageRef,
  markConnectionAttemptFailed,
  markConnectionAttemptStarted,
  navigatorRef,
  normalizeMqttHistoryConfig,
  normalizePeerId,
  normalizeUsbHint,
  normalizeWebSocketUrl,
  pickPortFromHint,
  setReconnectAfterReturn,
  setReconnectAfterReturnAttempted,
  storage,
  usbHintFromParams,
  usbHintLabel,
  usbStartupOptions,
  windowRef,
  wsDisplayName,
} = {}) {
  let connectionShellRegistry = null;

  function getConnectionShellRegistry() {
    if (connectionShellRegistry) return connectionShellRegistry;
    connectionShellRegistry = createConnectionShellRegistry({
      WebSerialTransport,
      WebSocketTransport,
      MqttTransport,
      MqttWebRtcTransport,
      alphaEnableWebRtcConnect,
      alphaEnableWebSocketConnect,
      connectionHistoryLimit,
      connectionKindAvailable,
      connectionKindIcon,
      connectionKindLabel,
      currentDeviceDisplayName,
      defaultPeerIdFromWebSocket,
      documentRef,
      fields,
      getClient,
      getConnectionHistoryActions,
      getConnectionMemoryService,
      getConnectionReconnectService,
      getConnectionTransportSession,
      getConsoleController,
      getMqttShellService,
      getTransport,
      isBusy,
      isConnectionVerified,
      isLoopbackHost,
      isMqttKind,
      isWebRtcKind,
      localStorageRef,
      markConnectionAttemptFailed,
      markConnectionAttemptStarted,
      navigatorRef,
      normalizeMqttHistoryConfig,
      normalizePeerId,
      normalizeUsbHint,
      normalizeWebSocketUrl,
      pickPortFromHint,
      setReconnectAfterReturn,
      setReconnectAfterReturnAttempted,
      storage,
      usbHintFromParams,
      usbHintLabel,
      usbStartupOptions,
      windowRef,
      wsDisplayName,
    });
    return connectionShellRegistry;
  }

  return {
    getConnectionAddressService: () => getConnectionShellRegistry().getConnectionAddressService(),
    getConnectionDialogController: () => getConnectionShellRegistry().getConnectionDialogController(),
    getConnectionDialogStateController: () => getConnectionShellRegistry().getConnectionDialogStateController(),
    getConnectionEntryController: () => getConnectionShellRegistry().getConnectionEntryController(),
    getConnectionHistoryStore: () => getConnectionShellRegistry().getConnectionHistoryStore(),
    getConnectionShellController: () => getConnectionShellRegistry().getConnectionShellController(),
    getConnectionShellRegistry,
    getConnectionUrlManager: () => getConnectionShellRegistry().getConnectionUrlManager(),
  };
}
