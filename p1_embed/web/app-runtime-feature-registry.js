import { createAppRuntimeRegistry } from "./app-runtime-registry.js?v=0.1.87-ui755";

export function createAppRuntimeFeatureRegistry({
  defaultPeerIdFromWebSocket,
  fields,
  getBugReportViewController,
  getChatSettings,
  getChatShellController,
  getCircuitShellController,
  getCircuitWorkspaceController,
  getCodeEditorShellController,
  getCommandConsoleService,
  getConnectionShellController,
  getConnectionAddressService,
  getConnectionTransportSession,
  getConnectionUiStateController,
  getConsoleController,
  getConsolePreferences,
  getDeviceRefreshService,
  getDeviceSettingsController,
  getEditorRegistry,
  getFirmwareUpdateController,
  getGenerativePanelController,
  getGuinoController,
  getGuinoShellService,
  getInfoPanelController,
  getInstallWorkflowController,
  getLowerPanelController,
  getProjectActionsController,
  getProjectDownloadService,
  getProjectHistoryView,
  getProjectToolbarController,
  getRevisionDraftStore,
  getScriptDownloadService,
  getScriptUploadService,
  getSettingsShellController,
  getSettingsTabs,
  getSpecificationEditorController,
  getUiActionRunner,
  getViewShellController,
  isBusy,
  isConnectionVerified,
  connectionIntentWanted,
  getClient,
  getTransport,
  getLastConfig,
  getLastStatus,
  mqttVersion,
  scriptToolbars,
  setReconnectAfterReturn,
  setUnloading,
  setWifiDraftDirty,
  storage,
  storageArea,
  syncGenerativePanelState,
  updateViewportHeight,
  webVersion,
  windowRef,
  documentRef,
  workspaceToolbars,
} = {}) {
  let appRuntimeRegistry = null;

  function getAppRuntimeRegistry() {
    if (appRuntimeRegistry) return appRuntimeRegistry;
    appRuntimeRegistry = createAppRuntimeRegistry({
      defaultPeerIdFromWebSocket,
      fields,
      getBugReportViewController,
      getChatSettings,
      getChatShellController,
      getCircuitShellController,
      getCircuitWorkspaceController,
      getCodeEditorShellController,
      getCommandConsoleService,
      getConnectionShellController,
      getConnectionAddressService,
      getConnectionTransportSession,
      getConnectionUiStateController,
      getConsoleController,
      getConsolePreferences,
      getDeviceRefreshService,
      getDeviceSettingsController,
      getEditorRegistry,
      getFirmwareUpdateController,
      getGenerativePanelController,
      getGuinoController,
      getGuinoShellService,
      getInfoPanelController,
      getInstallWorkflowController,
      getLowerPanelController,
      getProjectActionsController,
      getProjectDownloadService,
      getProjectHistoryView,
      getProjectToolbarController,
      getRevisionDraftStore,
      getScriptDownloadService,
      getScriptUploadService,
      getSettingsShellController,
      getSettingsTabs,
      getSpecificationEditorController,
      getUiActionRunner,
      getViewShellController,
      isBusy,
      isConnectionVerified,
      connectionIntentWanted,
      getClient,
      getTransport,
      getLastConfig,
      getLastStatus,
      mqttVersion,
      scriptToolbars,
      setReconnectAfterReturn,
      setUnloading,
      setWifiDraftDirty,
      storage,
      storageArea,
      syncGenerativePanelState,
      updateViewportHeight,
      webVersion,
      windowRef,
      documentRef,
      workspaceToolbars,
    });
    return appRuntimeRegistry;
  }

  return {
    getAppBootstrapController: () => getAppRuntimeRegistry().getAppBootstrapController(),
    getAppControlBindingsController: () => getAppRuntimeRegistry().getAppControlBindingsController(),
    getAppRuntimeRegistry,
    getPageLifecycleController: () => getAppRuntimeRegistry().getPageLifecycleController(),
  };
}
