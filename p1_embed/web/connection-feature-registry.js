import { ProtocolClient } from "./protocol/ProtocolClient.js?v=0.1.87-ui348";
import { canEncodeCommand } from "./protocol/P1MsgPack.js?v=0.1.87-ui348";
import { WebSerialTransport } from "./protocol/WebSerialTransport.js?v=0.1.87-ui350";
import { WebSocketTransport } from "./protocol/WebSocketTransport.js";
import { MqttWebRtcTransport } from "./protocol/MqttWebRtcTransport.js?v=0.1.87-ui348";
import { MqttTransport } from "./protocol/MqttTransport.js?v=0.1.87-ui349";
import { createConnectionRuntimeRegistry } from "./connection-runtime-registry.js?v=0.1.87-ui749";
import {
  isDroppedTransportState as isDroppedTransportStateFor,
  transportStateLogEntries,
} from "./connection-lifecycle-model.js?v=0.1.87-ui749";
import { currentDeviceDisplayName as currentDeviceDisplayNameFor } from "./status-model.js?v=0.1.87-ui749";

export function createConnectionFeatureRegistry({
  clearConnectionUrlParams,
  closeConnectDialog,
  connectionIntentWanted,
  documentRef,
  getClient,
  getCommandConsoleService,
  getConnectionAddressService,
  getConnectionHistoryStore,
  getConnectionMemoryService,
  getConnectionShellController,
  getConnectionStartupService,
  getConnectionUiStateController,
  getConnectionVerified,
  getConsoleController,
  getDeviceRefreshService,
  getDeviceStateController,
  getGeneration,
  getIsBusy,
  getIsUnloading,
  getLastConfig,
  getLastInfo,
  getLastStatus,
  getMqttShellService,
  getReconnectAfterReturn,
  getReconnectAfterReturnAttempted,
  getScriptDownloadService,
  getSuppressConnectionLogs,
  getTransport,
  isMqttKind,
  isWebRtcKind,
  localStorageRef,
  markConnectionAttemptFailed,
  markConnectionAttemptStarted,
  navigatorRef,
  normalizePeerId,
  normalizeWebSocketUrl,
  readRequestedLogLevel,
  readStoredLogLevel,
  renderConnectionState,
  setBusy,
  setBusyLabel,
  setClient,
  setConnected,
  setConnectionIntentWanted,
  setConnectionVerified,
  setGeneration,
  setPeerInput,
  setReconnectAfterReturn,
  setReconnectAfterReturnAttempted,
  setSuppressConnectionLogs,
  setTransport,
  setWebSocketInput,
  settle,
  startStatusPolling,
  stopStatusPolling,
  storage,
  updateEnabledState,
  windowRef,
  writeRequestedLogLevel,
  wsDisplayName,
} = {}) {
  let connectionRuntimeRegistry = null;

  function currentDeviceDisplayName() {
    return currentDeviceDisplayNameFor({
      lastInfo: getLastInfo?.(),
      lastStatus: getLastStatus?.(),
      lastConfig: getLastConfig?.(),
      normalizePeerId,
    });
  }

  function getConnectionRuntimeRegistry() {
    if (connectionRuntimeRegistry) return connectionRuntimeRegistry;
    connectionRuntimeRegistry = createConnectionRuntimeRegistry({
      ProtocolClient,
      WebSerialTransport,
      WebSocketTransport,
      MqttTransport,
      MqttWebRtcTransport,
      canEncodeCommand,
      clearConnectionUrlParams,
      closeConnectDialog,
      connectionIntentWanted,
      currentDeviceDisplayName,
      documentRef,
      getClient,
      getCommandConsoleService,
      getConnectionAddressService,
      getConnectionHistoryStore,
      getConnectionMemoryService,
      getConnectionShellController,
      getConnectionStartupService,
      getConnectionUiStateController,
      getConnectionVerified,
      getConsoleController,
      getDeviceRefreshService,
      getDeviceStateController,
      getGeneration,
      getIsBusy,
      getIsUnloading,
      getMqttShellService,
      getReconnectAfterReturn,
      getReconnectAfterReturnAttempted,
      getScriptDownloadService,
      getSuppressConnectionLogs,
      getTransport,
      isDroppedTransportState: isDroppedTransportStateFor,
      isMqttKind,
      isWebRtcKind,
      localStorageRef,
      markConnectionAttemptFailed,
      markConnectionAttemptStarted,
      navigatorRef,
      normalizePeerId,
      normalizeWebSocketUrl,
      readRequestedLogLevel,
      readStoredLogLevel,
      renderConnectionState,
      setBusy,
      setBusyLabel,
      setClient,
      setConnected,
      setConnectionIntentWanted,
      setConnectionVerified,
      setGeneration,
      setPeerInput,
      setReconnectAfterReturn,
      setReconnectAfterReturnAttempted,
      setSuppressConnectionLogs,
      setTransport,
      setWebSocketInput,
      settle,
      startStatusPolling,
      stopStatusPolling,
      storage,
      transportStateLogEntries,
      updateEnabledState,
      windowRef,
      writeRequestedLogLevel,
      wsDisplayName,
    });
    return connectionRuntimeRegistry;
  }

  return {
    getConnectionHistoryActions: () => getConnectionRuntimeRegistry().getConnectionHistoryActions(),
    getConnectionMemoryService: () => getConnectionRuntimeRegistry().getConnectionMemoryService(),
    getConnectionReconnectService: () => getConnectionRuntimeRegistry().getConnectionReconnectService(),
    getConnectionRuntimeRegistry,
    getConnectionStartupService: () => getConnectionRuntimeRegistry().getConnectionStartupService(),
    getConnectionTransportSession: () => getConnectionRuntimeRegistry().getConnectionTransportSession(),
  };
}
