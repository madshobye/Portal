export function presentationClassNames(...presentations) {
  const classes = [];
  for (const presentation of presentations.flatMap((value) => String(value || "").split(/\s+/))) {
    for (const className of PRESENTATION_CLASSES[presentation] || []) {
      if (!classes.includes(className)) classes.push(className);
    }
  }
  return classes;
}

export function presentationClassName(...presentations) {
  return presentationClassNames(...presentations).join(" ");
}

export function isKnownPresentation(presentation) {
  return Object.hasOwn(PRESENTATION_CLASSES, String(presentation || ""));
}
